using namespace std;
int main(){
    int t;
    cin>>t;
    while(t--){
        int n;
        cin>>n;
        int i=1;
        while(i<=n){
            cout<<i<<" ";
            i++;
        }
        i=1;
        while(i<=n){
            cout<<i<<" ";
            i++;
        }
        i=2;
        while(i<=n){
            cout<<i<<" ";
            i++;
        }
        cout<<"1"<<" ";
        int j=1;
        while(j<=n){
            cout<<j<<" ";
            j++;
        }
        cout<<endl;
    }
}